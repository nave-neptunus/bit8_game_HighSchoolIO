// node make_manifest.js : lists every PNG in assets/sprites/ so the game loads it (works from file:// too),
// and stamps a content hash on each script in index.html (?v=...) so browsers fetch fresh files after an update.
// Run it again after changing sprites or any .js file, before you commit.
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const hash = buf => crypto.createHash("md5").update(buf).digest("hex").slice(0, 8);
const dir = path.join(__dirname, "assets", "sprites");
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => f.toLowerCase().endsWith(".png")).sort() : [];
const ver = hash(Buffer.concat(files.map(f => fs.readFileSync(path.join(dir, f)))));
fs.writeFileSync(path.join(dir, "manifest.js"), "// generated by make_manifest.js\nwindow.SPRITE_VER = \"" + ver + "\";\nwindow.SPRITE_FILES = " + JSON.stringify(files, null, 1) + ";\n");
console.log(`${files.length} sprite file(s) listed in assets/sprites/manifest.js`);
const page = path.join(__dirname, "index.html");
const html = fs.readFileSync(page, "utf8").replace(/<script src="([^"?:]+\.js)(\?v=[^"]*)?"><\/script>/g, (m, src) =>
  `<script src="${src}?v=${hash(fs.readFileSync(path.join(__dirname, src)))}"></script>`);
fs.writeFileSync(page, html);
console.log("script versions stamped in index.html");
