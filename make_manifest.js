// node make_manifest.js : lists every PNG in assets/sprites/ so the game loads it (works from file:// too).
// Run it again after adding or removing sprites.
const fs = require("fs"), path = require("path");
const dir = path.join(__dirname, "assets", "sprites");
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => f.toLowerCase().endsWith(".png")).sort() : [];
fs.writeFileSync(path.join(dir, "manifest.js"), "// generated by make_manifest.js\nwindow.SPRITE_FILES = " + JSON.stringify(files, null, 1) + ";\n");
console.log(`${files.length} sprite file(s) listed in assets/sprites/manifest.js`);
